"use client";

import * as React from "react";
import { useRouter } from "next/navigation";
import { RotateCcw, TriangleAlert } from "lucide-react";

import { DemoResetDataSchema } from "@/lib/demo/reset-schema";
import { Button } from "@/components/ui/button";
import { useToast } from "@/components/ui/toast";
import { cn } from "@/lib/utils";

async function postReset(): Promise<{ ok: true; notice: string; summary: string } | { ok: false; message: string }> {
  let res: Response;
  try {
    // Client, same-origin, empty body: the server checks Origin/Host (loopback only) and DEMO_MODE.
    res = await fetch("/api/demo/reset", { method: "POST" });
  } catch {
    return { ok: false, message: "Could not reach the server. Check your connection and try again." };
  }
  let json: unknown = null;
  try {
    json = await res.json();
  } catch {
    // keep null
  }
  if (res.status === 200) {
    const parsed = DemoResetDataSchema.safeParse((json as { data?: unknown } | null)?.data);
    if (!parsed.success) return { ok: false, message: "The server returned a response this page could not read." };
    const d = parsed.data;
    return {
      ok: true,
      notice: d.notice,
      summary: `Restored ${d.recreated.evidence} sources, ${d.recreated.nodes} nodes and ${d.recreated.edges} edges; regenerated ${d.incidents.regenerated} incidents.`,
    };
  }
  const message = (json as { error?: { message?: string } } | null)?.error?.message;
  if (res.status === 403) {
    return {
      ok: false,
      message: `Reset is not allowed here${message ? `: ${message}` : ""}. It only works in demo mode from this machine.`,
    };
  }
  return { ok: false, message: `The reset failed${message ? `: ${message}` : ""}.` };
}

/**
 * FS-17 "Reset demo" control. Destructive, so it always asks first (native
 * <dialog>: focus is trapped and Escape cancels). Shown only in demo mode.
 */
export function ResetDemoButton({ compact = false, onDone }: { compact?: boolean; onDone?: () => void }) {
  const router = useRouter();
  const { toast } = useToast();
  const dialogRef = React.useRef<HTMLDialogElement>(null);
  const [pending, setPending] = React.useState(false);
  const titleId = React.useId();

  async function confirm() {
    setPending(true);
    const outcome = await postReset();
    setPending(false);
    dialogRef.current?.close();
    if (!outcome.ok) {
      toast({ title: "Demo not reset", description: outcome.message, variant: "danger" });
      return;
    }
    toast({ title: "Demo reset", description: `${outcome.notice} ${outcome.summary}`, variant: "success" });
    onDone?.();
    router.refresh(); // every page re-reads the restored data
  }

  return (
    <>
      <Button
        variant="ghost"
        size={compact ? "icon-sm" : "sm"}
        onClick={() => dialogRef.current?.showModal()}
        aria-label={compact ? "Reset demo data" : undefined}
        title="Reset demo data"
        className={cn(!compact && "justify-start")}
        data-testid="reset-demo-open"
      >
        <RotateCcw aria-hidden="true" />
        {compact ? null : <span>Reset demo</span>}
      </Button>
      <dialog
        ref={dialogRef}
        aria-labelledby={titleId}
        data-testid="reset-demo-dialog"
        className="m-auto w-[min(28rem,calc(100vw-2rem))] rounded-xl border border-border-strong bg-surface p-0 text-foreground shadow-2xl backdrop:bg-black/60"
      >
        <div className="flex flex-col gap-4 p-5">
          <h2 id={titleId} className="flex items-center gap-2 text-base font-semibold">
            <TriangleAlert aria-hidden="true" className="size-4 text-warning" />
            Reset the demo data?
          </h2>
          <p className="text-sm leading-relaxed text-muted">
            This deletes all simulations, proposals, reviews and audit history, and restores the fictional Northstar Labs
            fixture. Incidents are regenerated by the risk engine. No real data or Ramp account is affected.
          </p>
          <div className="flex flex-wrap justify-end gap-2">
            <Button variant="outline" onClick={() => dialogRef.current?.close()} disabled={pending} autoFocus>
              Cancel
            </Button>
            <Button variant="danger" onClick={confirm} disabled={pending} data-testid="reset-demo-confirm">
              <RotateCcw aria-hidden="true" />
              {pending ? "Resetting…" : "Reset demo data"}
            </Button>
          </div>
        </div>
      </dialog>
    </>
  );
}
