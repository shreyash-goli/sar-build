/**
 * Seed and reset for the fictional Northstar Labs demo workspace (FS-04).
 *
 * Both operations are transactional (one interactive transaction) and
 * deterministic: the fixture uses stable IDs and a fixed demo clock.
 *
 * Seed ("ensure") semantics, chosen to respect append-only evidence:
 *   - Missing fixture rows are created.
 *   - Rows that already exist and equal the fixture are left untouched, so
 *     re-running the seed is a no-op and never rewrites evidence.
 *   - Rows that exist but DIFFER from the fixture abort the whole seed with a
 *     ConflictError ("run pnpm demo:reset"). Seed never overwrites data.
 *
 * Reset semantics (the documented, named path that recreates evidence):
 *   - Requires DEMO_MODE. Clears ALL demo data through repos.demoReset.clearAllData()
 *     (incidents via incidents.deleteForDemoReset, which cascades to simulations
 *     and action proposals; audit events; graph; financial records; evidence),
 *     then reapplies the fixture, all in one transaction.
 *   - Incidents are NOT precomputed: after reseeding, the real risk engine
 *     (src/lib/incidents, FS-11) evaluates the workspace at the demo clock and
 *     materializes incidents inside the same transaction. Seed does the same
 *     (idempotent: an unchanged rerun writes nothing). Simulations and action
 *     proposals are only created by user actions (FS-14/15), so reset leaves
 *     them empty.
 */
import type { PrismaClient } from "@/generated/prisma/client";
import { isDemoModeEnabled } from "@/lib/env";
import {
  ConflictError,
  createRepositories,
  type DbClient,
  type DemoResetClearSummary,
  type Repositories,
} from "@/lib/repositories";
import { WriteForbiddenError } from "@/lib/security/write-gate";
import { loadNorthstarFixture, type DemoFixture } from "@/fixtures/northstar";
import { materializeIncidents, type MaterializeSummary } from "@/lib/incidents";
import { getNow } from "@/lib/time";

type Env = Readonly<Record<string, string | undefined>>;

export const SEED_COLLECTIONS = [
  "workspaces",
  "evidence",
  "fundingSources",
  "paymentInstruments",
  "vendors",
  "vendorCharges",
  "transactions",
  "nodes",
  "edges",
] as const;
export type SeedCollection = (typeof SEED_COLLECTIONS)[number];

export type SeedSummary = {
  fixtureId: string;
  fixtureVersion: number;
  created: Record<SeedCollection, number>;
  unchanged: Record<SeedCollection, number>;
  /** Incidents produced by the risk engine after the fixture was applied. */
  incidents: MaterializeSummary;
};

export type ResetSummary = {
  cleared: DemoResetClearSummary;
  seed: SeedSummary;
  /** Records regenerated by real logic (incidents) vs. user-action records never recreated (0). */
  regenerated: { incidents: number; simulations: 0; actionProposals: 0 };
};

export type DemoOptions = {
  /** Defaults to process.env. DEMO_MODE must be enabled. */
  env?: Env;
  /** Defaults to the bundled Northstar fixture. */
  fixture?: DemoFixture;
  /** Interactive transaction timeout in ms. */
  timeoutMs?: number;
};

export class DemoModeRequiredError extends WriteForbiddenError {
  constructor(operation: string) {
    super(`${operation} refused: DEMO_MODE must be "true" (demo data operations never run against non-demo workspaces)`);
    this.name = "DemoModeRequiredError";
  }
}

function assertDemo(env: Env, operation: string) {
  if (!isDemoModeEnabled(env)) throw new DemoModeRequiredError(operation);
}

function demoRepos(tx: DbClient, env: Env): Repositories {
  const gate = () => assertDemo(env, "Demo write");
  return createRepositories(tx, { writeGate: gate, demoResetGate: gate });
}

/** Key-order-independent JSON for equality checks. */
function canonical(value: unknown): string {
  return JSON.stringify(value, (_k, v: unknown) =>
    v && typeof v === "object" && !Array.isArray(v)
      ? Object.fromEntries(Object.entries(v as Record<string, unknown>).sort(([a], [b]) => a.localeCompare(b)))
      : v,
  );
}

type EnsureRepo = { findById(id: string): Promise<unknown>; create(input: unknown): Promise<unknown> };

async function applyFixture(repos: Repositories, fixture: DemoFixture): Promise<Omit<SeedSummary, "incidents">> {
  const rows: Record<SeedCollection, ReadonlyArray<{ id: string }>> = {
    workspaces: [fixture.workspace],
    evidence: fixture.evidence,
    fundingSources: fixture.fundingSources,
    paymentInstruments: fixture.paymentInstruments,
    vendors: fixture.vendors,
    vendorCharges: fixture.vendorCharges,
    transactions: fixture.transactions,
    nodes: fixture.nodes,
    edges: fixture.edges,
  };
  const created = Object.fromEntries(SEED_COLLECTIONS.map((c) => [c, 0])) as Record<SeedCollection, number>;
  const unchanged = { ...created };

  for (const collection of SEED_COLLECTIONS) {
    const repo = repos[collection] as EnsureRepo;
    for (const record of rows[collection]) {
      const existing = await repo.findById(record.id);
      if (existing === null) {
        await repo.create(record);
        created[collection] += 1;
      } else if (canonical(existing) === canonical(record)) {
        unchanged[collection] += 1;
      } else {
        throw new ConflictError(
          `Existing ${collection} record ${record.id} differs from the Northstar fixture; seed never overwrites data. Run \`pnpm demo:reset\` to restore the demo.`,
          { collection, id: record.id },
        );
      }
    }
  }
  return { fixtureId: fixture.meta.fixtureId, fixtureVersion: fixture.meta.version, created, unchanged };
}

/** Idempotent, transactional seed of the Northstar demo workspace. */
export async function seedNorthstarDemo(db: PrismaClient, options: DemoOptions = {}): Promise<SeedSummary> {
  const { env = process.env, fixture = loadNorthstarFixture(), timeoutMs = 30_000 } = options;
  assertDemo(env, "Demo seed");
  return db.$transaction(
    async (tx) => {
      const repos = demoRepos(tx, env);
      const applied = await applyFixture(repos, fixture);
      return { ...applied, incidents: await materializeIncidents(repos, getNow({ env })) };
    },
    { timeout: timeoutMs, maxWait: timeoutMs },
  );
}

/**
 * Transactional demo reset: clear everything, then reseed the fixture.
 * Reusable by scripts/reset-demo.ts and (later) POST /api/demo/reset.
 */
export async function resetNorthstarDemo(db: PrismaClient, options: DemoOptions = {}): Promise<ResetSummary> {
  const { env = process.env, fixture = loadNorthstarFixture(), timeoutMs = 30_000 } = options;
  assertDemo(env, "Demo reset");
  return db.$transaction(
    async (tx) => {
      const repos = demoRepos(tx, env);
      const cleared = await repos.demoReset.clearAllData();
      const applied = await applyFixture(repos, fixture);
      const incidents = await materializeIncidents(repos, getNow({ env }));
      return {
        cleared,
        seed: { ...applied, incidents },
        regenerated: { incidents: incidents.created.length, simulations: 0, actionProposals: 0 },
      } as const;
    },
    { timeout: timeoutMs, maxWait: timeoutMs },
  );
}
