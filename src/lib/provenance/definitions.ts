/**
 * User-readable definitions of evidence categories (synthetic vs observed vs
 * derived, plus suggested and unknown). Framework-free; safe for client code.
 * No runtime source is ever described as Ramp-documented.
 */
import type { SourceClass } from "../schema/enums";

export type EvidenceCategory = "synthetic" | "observed" | "derived" | "suggested" | "unknown";

export type EvidenceCategoryDefinition = {
  readonly category: EvidenceCategory;
  readonly label: string;
  readonly definition: string;
  /** What a reader may (and may not) conclude from this kind of evidence. */
  readonly howToRead: string;
  readonly sourceClasses: readonly SourceClass[];
};

